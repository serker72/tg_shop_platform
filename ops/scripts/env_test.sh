#!/usr/bin/env bash
# Generates an isolated test env file from the main (dev) env file.
# Usage: ops/scripts/env_test.sh <source .env> <target .env.test>
#        ops/scripts/env_test.sh --init <.env.example> <target .env>   (used by `make env`)
#
# --init mode: copies the template as is, replacing only secrets with random hex values
#   (URL-safe: they are embedded into URLs without escaping and read by `source`):
#   values starting with "change_me" -> openssl rand -hex 24; empty ENCRYPTION_KEY -> Fernet key
#   (urlsafe base64 of 32 random bytes, openssl only: no uv/python needed on the server);
#   empty POSTGRES_MONITORING_PASSWORD -> hex; empty CROWDSEC_BOUNCER_KEY -> openssl rand -hex 32.
#   URGENTRY_BOOTSTRAP_PASSWORD/PAT stay empty
#   (filled by ops/scripts/obs_bootstrap.sh). If the template has OBS_AUTH_HASH, Caddy Basic
#   Auth is generated by ops/scripts/obs_auth.sh (random password printed once, base64 bcrypt
#   hash via docker); without docker OBS_AUTH_HASH stays empty with a warning (make obs-auth).
#   Refuses to overwrite an existing target
#   (also if it appears during generation: published via `ln`, never clobbers);
#   the target has mode 600. Secret values are never printed.
#
# Rules:
#   source must be a dev file: PROJECT_DATA_DIR absolute and PROJECT_DATA_DIR/PROJECT_NAME
#   must not already end with "_test" (otherwise test and dev would share data);
#   POSTGRES_DB must be set and must not end with "_test" either;
#   PROJECT_ENVIRONMENT=test; PROJECT_NAME/PROJECT_DATA_DIR/POSTGRES_DB get a "_test" suffix
#   (integration fixtures refuse any database whose name does not end with "_test");
#   REDIS_DB is forced to 15 so the test cache never shares keys with the dev cache;
#   *_DATA_DIR are written as literal paths under the test PROJECT_DATA_DIR (order-independent);
#   *_PORT_HOST are shifted by PORT_OFFSET (default 20000), result must be within 1..65535;
#   MASTER_BOT_TOKEN -> mock; ENCRYPTION_KEYS_OLD -> empty;
#   ENCRYPTION_KEY is kept from an existing target file if valid, otherwise a new one is generated;
#   URGENTRY_BOOTSTRAP_PASSWORD / URGENTRY_BOOTSTRAP_PAT of the test obs stack are own values
#   (kept from an existing target file, otherwise generated); SENTRY_DSN, SENTRY_RELEASE -> empty;
#   PostgreSQL gets a small test profile regardless of the source (never the prod one):
#   PG_MEM_LIMIT=512m, PG_SHARED_BUFFERS=128MB, PG_EFFECTIVE_CACHE_SIZE=384MB,
#   PG_MAINTENANCE_WORK_MEM=64MB, PG_MAX_CONNECTIONS=50, PG_WORK_MEM=2MB, PG_AUTOVACUUM_WORK_MEM=32MB.
# Lines are normalized: CR, leading whitespace and "export " are stripped.
set -euo pipefail

gen_key() {
    uv run --quiet python -c \
        'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())'
}
valid_key() {
    uv run --quiet python -c \
        'import sys; from cryptography.fernet import Fernet; Fernet(sys.argv[1].encode())' \
        "$1" >/dev/null 2>&1
}

gen_fernet_key() {  # Fernet key = urlsafe base64 of 32 random bytes (44 chars, trailing '=')
    local k
    k=$(openssl rand -base64 32 | tr -d '\n' | tr '+/' '-_')
    [[ $k =~ ^[A-Za-z0-9_-]{43}=$ ]] || { echo "ERROR: could not generate ENCRYPTION_KEY" >&2; return 1; }
    printf '%s\n' "$k"
}
gen_hex() {
    local h
    h=$(openssl rand -hex 24)
    [[ $h =~ ^[0-9a-f]{48}$ ]] || { echo "ERROR: openssl rand failed" >&2; return 1; }
    printf '%s\n' "$h"
}

init_env() {  # --init <source> <target>: production-like env file with generated secrets
    local src=${1:-} dst=${2:-} tmp line key value secret generated=()
    local re='^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$'
    [[ -n $src && -n $dst ]] || { echo "usage: env_test.sh --init <source> <target>" >&2; exit 2; }
    [[ -f $src ]] || { echo "ERROR: $src not found" >&2; exit 1; }
    if [[ $(realpath -m "$src") == "$(realpath -m "$dst")" ]]; then
        echo "ERROR: source and target env files are the same file ($src)" >&2
        exit 1
    fi
    if [[ -e $dst ]]; then
        echo "ERROR: $dst already exists; refusing to overwrite (make env FORCE=1 backs it up)" >&2
        exit 1
    fi

    tmp=$(mktemp "$(dirname -- "$dst")/.$(basename -- "$dst").XXXXXX")
    # shellcheck disable=SC2064  # expand $tmp now: it is local to this function
    trap "rm -f -- '$tmp'" EXIT
    chmod 600 "$tmp"

    while IFS= read -r line || [[ -n $line ]]; do
        line=${line%$'\r'}
        if [[ $line =~ $re ]]; then
            key=${BASH_REMATCH[2]}
            value=${BASH_REMATCH[3]}
            value=${value#[\"\']}
            value=${value%[\"\']}
            if [[ $value == change_me* ]] \
                || [[ -z $value && $key == POSTGRES_MONITORING_PASSWORD ]]; then
                secret=$(gen_hex) || exit 1
                line="$key=$secret"
                generated+=("$key")
            elif [[ -z $value && $key == CROWDSEC_BOUNCER_KEY ]]; then
                secret=$(openssl rand -hex 32) || exit 1
                [[ $secret =~ ^[0-9a-f]{64}$ ]] || { echo "ERROR: openssl rand failed" >&2; exit 1; }
                line="$key=$secret"
                generated+=("$key")
            elif [[ -z $value && $key == ENCRYPTION_KEY ]]; then
                secret=$(gen_fernet_key) || exit 1
                line="$key=$secret"
                generated+=("$key")
            fi
        fi
        printf '%s\n' "$line"
    done <"$src" >"$tmp"

    # ln fails if dst already exists (no check-then-move race); tmp is in the same directory.
    if ! ln -- "$tmp" "$dst" 2>/dev/null; then
        echo "ERROR: could not create $dst (appeared during generation or hard links unsupported)" >&2
        exit 1
    fi
    rm -f -- "$tmp"
    trap - EXIT
    echo "Generated $dst from $src (mode 600)"
    echo "Generated secrets: ${generated[*]:-none}"
    if grep -qE '^[[:space:]]*(export[[:space:]]+)?OBS_AUTH_HASH=' "$dst"; then
        if bash "$(dirname -- "${BASH_SOURCE[0]}")/obs_auth.sh" "$dst" </dev/null; then
            echo "Generated Caddy Basic Auth: OBS_AUTH_USER / OBS_AUTH_HASH"
        else
            echo "WARNING: OBS_AUTH_HASH is empty: run make obs-auth before make obs-up" >&2
        fi
    fi
    echo "Fill in manually in $dst: MASTER_BOT_TOKEN (required);"
    echo "  ALERT_TELEGRAM_BOT_TOKEN / ALERT_TELEGRAM_CHAT_ID (alerts), CADDY_MODE + VPS_IP"
    echo "  (or GRAFANA_DOMAIN / URGENTRY_DOMAIN for CADDY_MODE=domain),"
    echo "  OBS_LOKI_PUSH_URL / OBS_PROMETHEUS_REMOTE_WRITE_URL (ALLOY_SINGLE_HOST), APP_UID / APP_GID."
}

if [[ ${1:-} == --init ]]; then
    init_env "${2:-}" "${3:-}"
    exit 0
fi

src=${1:?usage: env_test.sh <source> <target>}
dst=${2:?usage: env_test.sh <source> <target>}
port_offset=${PORT_OFFSET:-20000}

[[ -f $src ]] || { echo "ERROR: $src not found (make env)" >&2; exit 1; }
if [[ -e $dst && $(realpath "$src") == "$(realpath "$dst")" ]]; then
    echo "ERROR: source and target env files are the same file ($src)" >&2
    exit 1
fi

dst_value() {  # last value of KEY in an existing target file
    [[ -f $dst ]] || return 0
    tr -d '\r' <"$dst" \
        | sed -nE "s/^[[:space:]]*(export[[:space:]]+)?$1=//p" \
        | tail -n1 | tr -d "\"'"
}

key=$(dst_value ENCRYPTION_KEY)
# Own urgentry bootstrap secrets for the test obs stack (stable across regenerations,
# otherwise the existing test owner/PAT would not match).
gt_password=$(dst_value URGENTRY_BOOTSTRAP_PASSWORD)
[[ $gt_password =~ ^[0-9a-f]{48}$ ]] || gt_password=$(openssl rand -hex 24)
gt_public_key=$(dst_value URGENTRY_BOOTSTRAP_PAT)
[[ $gt_public_key =~ ^[0-9a-f]{48}$ ]] || gt_public_key=$(openssl rand -hex 24)
key_msg="Keeping existing ENCRYPTION_KEY from $dst"
if [[ -z $key ]] || ! valid_key "$key"; then
    key=$(gen_key)
    key_msg="Generated new ENCRYPTION_KEY for $dst"
fi

tmp=$(mktemp "${dst}.XXXXXX")
trap 'rm -f "$tmp"' EXIT

awk -v key="$key" -v tenv="$dst" -v off="$port_offset" -v gtpw="$gt_password" -v gtpk="$gt_public_key" '
function norm(s) { gsub(/\r/, "", s); sub(/^[[:space:]]+/, "", s); sub(/^export[[:space:]]+/, "", s); return s }
function unq(s) { if (s ~ /^".*"$/ || s ~ /^\047.*\047$/) return substr(s, 2, length(s) - 2); return s }
function trim(s) { sub(/^[[:space:]]+/, "", s); sub(/[[:space:]]+$/, "", s); return s }
function strip(s) { s = trim(unq(trim(s))); sub(/\/+$/, "", s); return s }
function fail(msg) { print "ERROR: " msg > "/dev/stderr"; err = 1; exit 2 }
function port(k, v,  p, r) {
    p = unq(v); if (p == "") p = pd[k]
    if (p !~ /^[0-9]+$/) fail(k "=" p " is not a number")
    r = p + off
    if (p < 1 || r > 65535) fail(k "=" p " + offset " off " = " r " is outside 1..65535")
    return r
}
BEGIN {
    dd["POSTGRES_DATA_DIR"] = "db"; dd["REDIS_DATA_DIR"] = "redis"; dd["RABBITMQ_DATA_DIR"] = "rabbitmq"
    dd["MINIO_DATA_DIR"] = "minio"; dd["LOGS_DATA_DIR"] = "logs"
    # observability stack (docker-compose.obs.yml)
    dd["OBS_URGENTRY_DATA_DIR"] = "obs/urgentry"; dd["OBS_TEMPO_DATA_DIR"] = "obs/tempo"
    dd["OBS_GRAFANA_DATA_DIR"] = "obs/grafana"; dd["OBS_PROMETHEUS_DATA_DIR"] = "obs/prometheus"
    dd["OBS_LOKI_DATA_DIR"] = "obs/loki"; dd["OBS_ALERTMANAGER_DATA_DIR"] = "obs/alertmanager"
    dd["OBS_CADDY_DATA_DIR"] = "obs/caddy"; dd["OBS_CADDY_LOGS_DIR"] = "obs/caddy-logs"
    dd["OBS_CROWDSEC_DATA_DIR"] = "obs/crowdsec"
    dd["ALLOY_DATA_DIR"] = "alloy"  # collection agent (docker-compose.yml, profile observability)
    pd["POSTGRES_PORT_HOST"] = 5432; pd["REDIS_PORT_HOST"] = 6379; pd["RABBITMQ_PORT_HOST"] = 5672
    pd["RABBITMQ_MGMT_PORT_HOST"] = 15672; pd["MINIO_API_PORT_HOST"] = 9000; pd["MINIO_CONSOLE_PORT_HOST"] = 9001
    pd["GRAFANA_PORT_HOST"] = 3000; pd["LOKI_PORT_HOST"] = 3100; pd["PROMETHEUS_PORT_HOST"] = 9090
    pd["ALERTMANAGER_PORT_HOST"] = 9093; pd["URGENTRY_PORT_HOST"] = 8000
    pd["TEMPO_OTLP_GRPC_PORT_HOST"] = 4317; pd["TEMPO_OTLP_HTTP_PORT_HOST"] = 4318; pd["TEMPO_PORT_HOST"] = 3200
    pd["CADDY_HTTP_PORT_HOST"] = 80; pd["CADDY_HTTPS_PORT_HOST"] = 443
    pd["ALLOY_PORT_HOST"] = 12345
    # small PostgreSQL profile of the test stack (overrides the prod values of the source)
    tv["PG_MEM_LIMIT"] = "512m"; tv["PG_SHARED_BUFFERS"] = "128MB"; tv["PG_EFFECTIVE_CACHE_SIZE"] = "384MB"
    tv["PG_MAINTENANCE_WORK_MEM"] = "64MB"; tv["PG_MAX_CONNECTIONS"] = "50"
    tv["PG_WORK_MEM"] = "2MB"; tv["PG_AUTOVACUUM_WORK_MEM"] = "32MB"
}
# Pass 1: collect and validate PROJECT_DATA_DIR / PROJECT_NAME.
FNR == NR {
    line = norm($0)
    if (line ~ /^#/ || index(line, "=") == 0) next
    k = substr(line, 1, index(line, "=") - 1); v = strip(substr(line, index(line, "=") + 1))
    if (k == "PROJECT_DATA_DIR") { pdir = v; has_pdir = 1 }
    if (k == "PROJECT_NAME") pname = v
    if (k == "POSTGRES_DB") { pgdb = v; has_pgdb = 1 }
    next
}
FNR == 1 {
    if (!has_pdir || pdir == "") fail("PROJECT_DATA_DIR is empty or missing in source env")
    if (pdir !~ /^\// || pdir ~ /\$/) fail("PROJECT_DATA_DIR must be an absolute literal path, got: " pdir)
    if (pdir ~ /_test$/) fail("PROJECT_DATA_DIR already ends with _test; source must be the dev env file")
    if (pname ~ /_test$/) fail("PROJECT_NAME already ends with _test; source must be the dev env file")
    if (!has_pgdb || pgdb == "") fail("POSTGRES_DB is empty or missing in source env")
    if (pgdb ~ /_test$/) fail("POSTGRES_DB already ends with _test; source must be the dev env file")
    tdir = pdir "_test"
}
# Pass 2: write the test env.
{
    line = norm($0)
    if (line == "" || line ~ /^#/ || index(line, "=") == 0) { print line; next }
    k = substr(line, 1, index(line, "=") - 1); v = substr(line, index(line, "=") + 1); seen[k] = 1
}
k == "PROJECT_ENVIRONMENT"  { print k "=test"; next }
k == "PROJECT_NAME"         { print k "=\"" strip(v) "_test\""; next }
k == "PROJECT_DATA_DIR"     { print k "=\"" tdir "\""; next }
k == "POSTGRES_DB"          { print k "=\"" pgdb "_test\""; next }
k == "REDIS_DB"             { print k "=15"; next }  # isolated test cache, never the dev one
k in dd                     { print k "=\"" tdir "/" dd[k] "\""; next }
k in pd                     { print k "=" port(k, v); next }
k in tv                     { print k "=" tv[k]; next }
k == "MASTER_BOT_TOKEN"     { print k "=123456789:TEST-mock-master-bot-token"; next }
k == "ENCRYPTION_KEY"       { print k "=" key; next }
k == "ENCRYPTION_KEYS_OLD"  { print k "="; next }
k == "ALERT_TELEGRAM_BOT_TOKEN" || k == "ALERT_TELEGRAM_CHAT_ID" { print k "="; next }  # no test alerts to the real chat
k == "APP_ENV_FILE"         { print k "=" tenv; next }
k == "URGENTRY_BOOTSTRAP_PASSWORD"     { print k "=" gtpw; next }  # own test obs stack values
k == "URGENTRY_BOOTSTRAP_PAT" { print k "=" gtpk; next }
k == "SENTRY_DSN"           { print k "="; next }  # test app never reports to urgentry
k == "SENTRY_RELEASE"       { print k "="; next }  # computed from the app version
{ print line }
END {
    if (err) exit 2
    print ""; print "# --- added by ops/scripts/env_test.sh ---"
    for (k in dd) if (!(k in seen)) print k "=\"" tdir "/" dd[k] "\""
    for (k in pd) if (!(k in seen)) print k "=" port(k, "")
    for (k in tv) if (!(k in seen)) print k "=" tv[k]
    if (err) exit 2
    if (!("ENCRYPTION_KEY" in seen)) print "ENCRYPTION_KEY=" key
    if (!("URGENTRY_BOOTSTRAP_PASSWORD" in seen)) print "URGENTRY_BOOTSTRAP_PASSWORD=" gtpw
    if (!("URGENTRY_BOOTSTRAP_PAT" in seen)) print "URGENTRY_BOOTSTRAP_PAT=" gtpk
    if (!("SENTRY_DSN" in seen)) print "SENTRY_DSN="
    if (!("SENTRY_RELEASE" in seen)) print "SENTRY_RELEASE="
    if (!("APP_ENV_FILE" in seen)) { print "# Env file passed to app containers (docker-compose env_file)"; print "APP_ENV_FILE=" tenv }
}
' "$src" "$src" >"$tmp"

mv "$tmp" "$dst"
trap - EXIT
echo "$key_msg"
echo "Generated $dst from $src (host ports +$port_offset)"
