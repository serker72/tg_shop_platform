"""Safety guards of the integration fixtures (importable without infrastructure).

They protect the dev database: integration fixtures commit, run DDL and TRUNCATE, so they
must only ever touch the isolated test stack generated by ``make env-test``.
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import shutil
import subprocess  # noqa: S404 - read-only queries against the local Docker socket
from collections.abc import Iterable
from pathlib import Path
from typing import NoReturn

import pytest
from aio_pika.connection import make_url as make_amqp_url
from aiormq.connection import Connection as AMQPConnection
from faststream.rabbit import RabbitBroker
from sqlalchemy.engine import make_url
from yarl import URL

from app.core.config import Settings

__all__ = [
    "CLEAN_DB_INCOMPATIBLE",
    "TEST_DB_SUFFIX",
    "DatabaseTarget",
    "assert_clean_db_compatible",
    "assert_same_database",
    "assert_test_database",
    "assert_test_database_name",
    "database_target",
    "guarded_rabbit_broker",
    "guarded_rabbit_url",
    "infra_unavailable",
]

#: ``(host, port, database)`` of a DSN - identifies the server-side database, no secrets.
DatabaseTarget = tuple[str, int, str]

TEST_DB_SUFFIX = "_test"

#: Fixtures that hold the never-committed outer transaction; TRUNCATE in ``clean_db`` would
#: wait for its locks forever (``lock_timeout`` defaults to 0).
CLEAN_DB_INCOMPATIBLE = frozenset({"db_connection", "session", "session_factory"})

_HOW_TO_FIX = "run `make env-test` and use `make test-integration` (it exports the test stack)"


def infra_unavailable(reason: str) -> NoReturn:
    """Skip, or fail when ``REQUIRE_INFRA=1`` (``make test-integration``) demands the infra."""
    if os.environ.get("REQUIRE_INFRA") == "1":
        pytest.fail(f"REQUIRE_INFRA=1 but {reason}")
    pytest.skip(reason)


def assert_test_database(settings: Settings) -> None:
    """Refuse non-test settings before any connection is opened.

    Requires ``PROJECT_ENVIRONMENT=test`` and a ``POSTGRES_DB`` ending with ``_test``; a
    missing ``.env.test`` falls back to the dev defaults and is rejected here as well.
    The message names the database and environment, never the password.
    """
    environment = settings.project_environment
    database = settings.postgres.db
    if environment != "test":
        infra_unavailable(
            f"PROJECT_ENVIRONMENT={environment!r} is not 'test' (database {database!r}); "
            f"refusing to touch a non-test database: {_HOW_TO_FIX}"
        )
    if not database.endswith(TEST_DB_SUFFIX):
        infra_unavailable(
            f"POSTGRES_DB={database!r} does not end with {TEST_DB_SUFFIX!r}; "
            f"refusing to touch a non-test database: {_HOW_TO_FIX}"
        )


def _docker_output(*args: str) -> str:
    docker = shutil.which("docker")
    if docker is None or not Path(docker).is_absolute():
        raise FileNotFoundError("Docker CLI unavailable")
    return subprocess.check_output(  # noqa: S603 - fixed Docker commands and validated IDs
        [docker, "--host", "unix:///var/run/docker.sock", *args],
        stdin=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        timeout=10,
    ).decode("utf-8")


def _local_test_rabbit_target() -> tuple[str, int, str]:
    """Read only the selected container's non-secret metadata and live vhost names."""
    checkout = Path(__file__).resolve().parents[2]
    ids = _docker_output("ps", "-q", "--filter", "label=com.docker.compose.service=rabbitmq")
    candidates = []
    for container in ids.strip().splitlines():
        if not re.fullmatch(r"[0-9a-f]{12,64}", container):
            raise ValueError("invalid container ID")
        template = (
            "{{json .Config.Labels}}\n{{json .Mounts}}\n"
            '{{json (index .NetworkSettings.Ports "5672/tcp")}}'
        )
        rows = _docker_output("inspect", "-f", template, container).strip().splitlines()
        labels, mounts, ports = map(json.loads, rows)
        if (
            labels.get("com.docker.compose.service") != "rabbitmq"
            or not labels.get("com.docker.compose.project", "").endswith(TEST_DB_SUFFIX)
            or labels.get("com.docker.compose.oneoff", "").lower() != "false"
            or labels.get("com.docker.compose.project.working_dir") != str(checkout)
        ):
            continue
        data = [m for m in mounts if m.get("Destination") == "/var/lib/rabbitmq"]
        if len(data) != 1 or data[0].get("Type") != "bind":
            continue
        source = Path(data[0]["Source"])
        if not source.is_absolute() or any(
            path.name != "rabbitmq" or not path.parent.name.endswith(TEST_DB_SUFFIX)
            for path in (source, source.resolve())
        ):
            continue
        if not ports or len(ports) != 1 or ports[0].get("HostIp") != "127.0.0.1":
            continue
        port = int(ports[0]["HostPort"])
        if 0 < port < 65536:
            candidates.append((container, port))
    if len(candidates) != 1:
        raise ValueError("missing or ambiguous test RabbitMQ metadata")
    container, port = candidates[0]
    # Query just the provisioned vhost key, never the entire container environment.
    provisioned = _docker_output("exec", container, "printenv", "RABBITMQ_DEFAULT_VHOST")
    if not provisioned.endswith("\n"):
        raise ValueError("incomplete provisioned vhost metadata")
    vhost = provisioned.removesuffix("\n")
    live = json.loads(
        _docker_output(
            "exec", container, "rabbitmqctl", "-q", "--formatter=json", "list_vhosts", "name"
        )
    )
    if not isinstance(live, list) or not all(
        isinstance(row, dict) and isinstance(row.get("name"), str) for row in live
    ):
        raise ValueError("invalid live vhost metadata")
    if not vhost or not any(row["name"] == vhost for row in live):
        raise ValueError("configured test vhost does not exist")
    return "127.0.0.1", port, vhost


def _effective_amqp_target(dsn: str | URL) -> tuple[str, str | None, int | None, str]:
    # Use the same URL parser and vhost resolution as aio-pika/aiormq. Constructing
    # the client allocates local state only; never call connect from the guard.
    loop = asyncio.new_event_loop()
    try:
        connection = AMQPConnection(make_amqp_url(dsn), loop=loop)
        return connection.url.scheme, connection.url.host, connection.url.port, connection.vhost
    finally:
        loop.close()


def _metadata_target() -> tuple[str, int, str] | None:
    try:
        return _local_test_rabbit_target()
    except (OSError, subprocess.SubprocessError, ValueError, TypeError, KeyError, AttributeError):
        return None


def _checked_settings_url(settings: Settings, expected: tuple[str, int, str]) -> str | None:
    try:
        dsn = settings.rabbitmq_url
        return dsn if _effective_amqp_target(dsn) == ("amqp", *expected) else None
    except Exception:  # noqa: BLE001 - drop potentially sensitive parser errors before pytest.fail
        return None


def _prepared_broker_matches(broker: RabbitBroker, expected: tuple[str, int, str]) -> bool:
    try:
        # FastStream 0.7.8 passes this mapping to aio-pika's connect_robust.
        url = broker._connection_kwargs["url"]
        return isinstance(url, (str, URL)) and _effective_amqp_target(url) == ("amqp", *expected)
    except Exception:  # noqa: BLE001 - missing/changed FastStream internals must fail closed
        return False


def _settings_target(settings: Settings) -> tuple[str, int, str]:
    assert_test_database(settings)
    expected = _metadata_target()
    rabbit = settings.rabbitmq
    matches = (rabbit.host, rabbit.port, rabbit.vhost) == expected
    del settings, rabbit
    if expected is None:
        infra_unavailable("isolated RabbitMQ metadata unavailable or invalid")
    if not matches:
        del expected
        pytest.fail("settings do not match the isolated RabbitMQ endpoint and vhost")
    return expected


def guarded_rabbit_url(settings: Settings) -> str:
    """Authorize AMQP only after comparison against independent local Compose metadata."""
    expected = _settings_target(settings)
    checked = _checked_settings_url(settings, expected)
    if checked is None:
        del settings, expected
        pytest.fail("effective AMQP destination does not match the isolated RabbitMQ endpoint")
    return checked


def guarded_rabbit_broker(broker: RabbitBroker, test_settings: Settings) -> RabbitBroker:
    """Verify and return the same prepared FastStream instance before connecting."""
    # Capture metadata failure outside the frame holding the broker; the URL
    # and parser exceptions stay in the non-raising helpers above.
    expected = _metadata_target()
    matches = expected is not None and _prepared_broker_matches(broker, expected)
    is_test = test_settings.project_environment == "test" and test_settings.postgres.db.endswith(
        TEST_DB_SUFFIX
    )
    if not is_test or not matches:
        del broker, test_settings, expected
        pytest.fail("prepared AMQP destination does not match the isolated RabbitMQ endpoint")
    return broker


def assert_test_database_name(current_database: str) -> None:
    """Fail (never skip) when the server-side ``current_database()`` is not a test one."""
    if not current_database.endswith(TEST_DB_SUFFIX):
        pytest.fail(
            f"connected to database {current_database!r}, which does not end with "
            f"{TEST_DB_SUFFIX!r}; aborting before migrations"
        )


def database_target(database_url: str) -> DatabaseTarget:
    """Extract ``(host, port, database)`` from a DSN (the password is dropped)."""
    url = make_url(database_url)
    return (url.host or "", url.port or 5432, url.database or "")


def assert_same_database(migrated: DatabaseTarget, database_url: str) -> None:
    """Fail when ``database_url`` points elsewhere than the database ``migrated_db`` checked.

    Protects against a module overriding ``settings`` (e.g. with dev ``Settings()``): the
    guards and migrations ran on the test database, but ``engine``/``clean_db`` would then
    commit and TRUNCATE elsewhere. Only host/port/database appear in the message.
    """
    actual = database_target(database_url)
    if actual != migrated:
        pytest.fail(
            "engine settings point to {}:{}/{} but migrated_db verified {}:{}/{}; "
            "do not override `settings` for database tests".format(*actual, *migrated)
        )


def assert_clean_db_compatible(fixturenames: Iterable[str]) -> None:
    """Fail when ``clean_db`` is combined with the outer-transaction fixtures."""
    clashing = sorted(CLEAN_DB_INCOMPATIBLE.intersection(fixturenames))
    if clashing:
        pytest.fail(
            "clean_db is incompatible with session/session_factory/db_connection: "
            f"TRUNCATE would wait for the outer transaction (requested: {', '.join(clashing)})"
        )
