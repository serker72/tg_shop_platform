"""Safety guards of the integration fixtures (importable without infrastructure).

They protect the dev database: integration fixtures commit, run DDL and TRUNCATE, so they
must only ever touch the isolated test stack generated by ``make env-test``.
"""

from __future__ import annotations

import os
from collections.abc import Iterable
from typing import NoReturn

import pytest
from sqlalchemy.engine import make_url

from app.core.config import Settings

__all__ = [
    "CLEAN_DB_INCOMPATIBLE",
    "TEST_DB_SUFFIX",
    "DatabaseTarget",
    "assert_clean_db_compatible",
    "assert_same_database",
    "assert_test_database",
    "assert_test_database_name",
    "database_target",
    "infra_unavailable",
]

#: ``(host, port, database)`` of a DSN - identifies the server-side database, no secrets.
DatabaseTarget = tuple[str, int, str]

TEST_DB_SUFFIX = "_test"

#: Fixtures that hold the never-committed outer transaction; TRUNCATE in ``clean_db`` would
#: wait for its locks forever (``lock_timeout`` defaults to 0).
CLEAN_DB_INCOMPATIBLE = frozenset({"db_connection", "session", "session_factory"})

_HOW_TO_FIX = "run `make env-test` and use `make test-integration` (it exports the test stack)"


def infra_unavailable(reason: str) -> NoReturn:
    """Skip, or fail when ``REQUIRE_INFRA=1`` (``make test-integration``) demands the infra."""
    if os.environ.get("REQUIRE_INFRA") == "1":
        pytest.fail(f"REQUIRE_INFRA=1 but {reason}")
    pytest.skip(reason)


def assert_test_database(settings: Settings) -> None:
    """Refuse non-test settings before any connection is opened.

    Requires ``PROJECT_ENVIRONMENT=test`` and a ``POSTGRES_DB`` ending with ``_test``; a
    missing ``.env.test`` falls back to the dev defaults and is rejected here as well.
    The message names the database and environment, never the password.
    """
    environment = settings.project_environment
    database = settings.postgres.db
    if environment != "test":
        infra_unavailable(
            f"PROJECT_ENVIRONMENT={environment!r} is not 'test' (database {database!r}); "
            f"refusing to touch a non-test database: {_HOW_TO_FIX}"
        )
    if not database.endswith(TEST_DB_SUFFIX):
        infra_unavailable(
            f"POSTGRES_DB={database!r} does not end with {TEST_DB_SUFFIX!r}; "
            f"refusing to touch a non-test database: {_HOW_TO_FIX}"
        )


def assert_test_database_name(current_database: str) -> None:
    """Fail (never skip) when the server-side ``current_database()`` is not a test one."""
    if not current_database.endswith(TEST_DB_SUFFIX):
        pytest.fail(
            f"connected to database {current_database!r}, which does not end with "
            f"{TEST_DB_SUFFIX!r}; aborting before migrations"
        )


def database_target(database_url: str) -> DatabaseTarget:
    """Extract ``(host, port, database)`` from a DSN (the password is dropped)."""
    url = make_url(database_url)
    return (url.host or "", url.port or 5432, url.database or "")


def assert_same_database(migrated: DatabaseTarget, database_url: str) -> None:
    """Fail when ``database_url`` points elsewhere than the database ``migrated_db`` checked.

    Protects against a module overriding ``settings`` (e.g. with dev ``Settings()``): the
    guards and migrations ran on the test database, but ``engine``/``clean_db`` would then
    commit and TRUNCATE elsewhere. Only host/port/database appear in the message.
    """
    actual = database_target(database_url)
    if actual != migrated:
        pytest.fail(
            "engine settings point to {}:{}/{} but migrated_db verified {}:{}/{}; "
            "do not override `settings` for database tests".format(*actual, *migrated)
        )


def assert_clean_db_compatible(fixturenames: Iterable[str]) -> None:
    """Fail when ``clean_db`` is combined with the outer-transaction fixtures."""
    clashing = sorted(CLEAN_DB_INCOMPATIBLE.intersection(fixturenames))
    if clashing:
        pytest.fail(
            "clean_db is incompatible with session/session_factory/db_connection: "
            f"TRUNCATE would wait for the outer transaction (requested: {', '.join(clashing)})"
        )
